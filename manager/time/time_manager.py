"""EN: Time tracking manager for game session and gameplay.
RU: ???????? ????? ??????? ??? ?????? ? ????????.
"""

from __future__ import annotations

from time import perf_counter


class TimeManager:
    """EN: Track game session and gameplay durations using a monotonic timer.
    RU: ??????????? ???????????? ?????? ? ???????? ? ?????????? ????????.
    """

    def __init__(self) -> None:
        """EN: Initialize time manager state.
        RU: ???????????????? ????????? ????????? ???????.
        """
        self._session_t0 = None
        self._session_elapsed = 0.0
        self._gameplay_t0 = None
        self._gameplay_elapsed = 0.0

    def _time_value(self, started_at: float | None, elapsed: float) -> float:
        """EN: Return accumulated elapsed time including the currently running segment.
        RU: ??????? ??????????? ????? ? ?????? ???????? ????????? ????????.
        """
        if started_at is None:
            return float(elapsed)
        return float(elapsed) + (perf_counter() - started_at)

    def pause_game_session(self) -> float:
        """EN: Pause session timer without resetting accumulated duration.
        RU: ????????? ?????? ?????? ?? ????? ??? ?????? ??????????? ????????????.
        """
        self._session_elapsed = self._time_value(self._session_t0, self._session_elapsed)
        self._session_t0 = None
        return self._session_elapsed

    def resume_game_session(self) -> None:
        """EN: Resume session timer from the current accumulated value.
        RU: ??????????? ?????? ?????? ? ???????? ???????????? ????????.
        """
        if self._session_t0 is None:
            self._session_t0 = perf_counter()

    def pause_gameplay(self) -> float:
        """EN: Pause gameplay timer without resetting accumulated duration.
        RU: ????????? ?????? ???????? ?? ????? ??? ?????? ??????????? ????????????.
        """
        self._gameplay_elapsed = self._time_value(self._gameplay_t0, self._gameplay_elapsed)
        self._gameplay_t0 = None
        return self._gameplay_elapsed

    def resume_gameplay(self) -> None:
        """EN: Resume gameplay timer from the current accumulated value.
        RU: ??????????? ?????? ???????? ? ???????? ???????????? ????????.
        """
        if self._gameplay_t0 is None:
            self._gameplay_t0 = perf_counter()

    def time_game_session(self, start: bool = False, stop: bool = False, reset: bool = False) -> float | None:
        """EN: Start, stop, reset, pause-safe resume, or get the current session duration.
        RU: ?????????, ??????????, ????????, ????????? ??????????? ??? ???????? ???????????? ??????.
        """
        if reset:
            self._session_t0 = None
            self._session_elapsed = 0.0
        if start:
            self._session_elapsed = 0.0
            self._session_t0 = perf_counter()
        if stop:
            return self.pause_game_session()
        return self._time_value(self._session_t0, self._session_elapsed)

    def time_gameplay(self, start: bool = False, stop: bool = False, reset: bool = False) -> float | None:
        """EN: Start, stop, reset, pause-safe resume, or get the gameplay duration.
        RU: ?????????, ??????????, ????????, ????????? ??????????? ??? ???????? ???????????? ????????.
        """
        if reset:
            self._gameplay_t0 = None
            self._gameplay_elapsed = 0.0
        if start:
            self._gameplay_elapsed = 0.0
            self._gameplay_t0 = perf_counter()
        if stop:
            return self.pause_gameplay()
        return self._time_value(self._gameplay_t0, self._gameplay_elapsed)
