from __future__ import annotations

from kivy.clock import Clock
from kivy.core.window import Window
from kivy.uix.textinput import TextInput


def _iter_focusable_inputs(widget):
    """EN: Yield all text-input widgets reachable from the provided screen/widget tree.
    RU: ??????? ??? text-input ???????, ?????????? ?? ??????????? ?????? screen/widget.
    """
    if isinstance(widget, TextInput):
        yield widget
    for child in getattr(widget, "children", []):
        yield from _iter_focusable_inputs(child)


def _blur_inputs(widget) -> None:
    """EN: Remove focus from every text input inside the widget tree and close soft keyboards.
    RU: ????? ????? ?? ???? text-input ?????? ?????? ???????? ? ??????? soft keyboard.
    """
    for input_widget in _iter_focusable_inputs(widget):
        input_widget.focus = False
    try:
        Window.release_all_keyboards()
    except Exception:
        pass


def blur_inputs_on_screen_enter(widget) -> None:
    """EN: Clear input focus immediately and once more on the next frame for stable screen-entry behavior.
    RU: ????? ????? ? ????? ????? ? ???????? ?? ????????? ????? ??? ??????????? ????????? ??? ????? ?? ?????.
    """
    _blur_inputs(widget)
    Clock.schedule_once(lambda _dt: _blur_inputs(widget), 0)
